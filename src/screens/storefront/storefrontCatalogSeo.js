function catalogSeoKey(route) {
  if (!route || route.name !== "catalog" || route.facet) return "";
  const category = String(route.category || "").trim();
  if (!category) return "";
  const subcategory = String(route.subcategory || "").trim();
  return subcategory ? `${category}\0${subcategory}` : category;
}

/** @returns {{ title: string, h1: string, description: string } | null} */
export function getCatalogPageSeo(route) {
  const key = catalogSeoKey(route);
  if (!key) return null;
  return OVERRIDES[key] || null;
}

/** @returns {string | null} */
export function getCatalogPageH1(route) {
  return getCatalogPageSeo(route)?.h1 ?? null;
}

export function listCatalogSeoOverridePaths() {
  return Object.keys(OVERRIDES).map((key) => {
    const [category, subcategory] = key.split("\0");
    return { category, subcategory: subcategory || undefined };
  });
}
