function catalogContentKey(route) {
  if (!route || route.name !== "catalog" || route.facet) return "";
  const category = String(route.category || "").trim();
  if (!category) return "";
  const subcategory = String(route.subcategory || "").trim();
  return subcategory ? `${category}\u0000${subcategory}` : category;
}

/** @returns {CatalogPageContent | null} */
export function getCatalogPageContent(route) {
  const key = catalogContentKey(route);
  if (!key) return null;
  return CONTENT[key] || null;
}

export function listCatalogContentPaths() {
  return Object.keys(CONTENT).map((key) => {
    const [category, subcategory] = key.split("\u0000");
    return { category, subcategory: subcategory || undefined };
  });
}
