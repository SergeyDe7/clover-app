const BY_CATEGORY = new Map(RECORDS.map((record) => [record.category, record]));

function isBlank(value) {
  return value == null || String(value).trim() === "";
}

/**
 * @param {{
 *   category?: string | null,
 *   subcategory?: string | null,
 *   facet?: string | null,
 *   locale?: string | null,
 * }} input
 * @returns {typeof RECORDS[number] | null}
 */
export function resolveCategoryCommercialSeo({
  category = "",
  subcategory = "",
  facet = "",
  locale = "ru",
} = {}) {
  if (String(locale || "").trim() !== "ru") return null;
  if (isBlank(category) || !isBlank(subcategory) || !isBlank(facet)) return null;
  return BY_CATEGORY.get(String(category).trim()) || null;
}

/** @returns {ReadonlyArray<(typeof RECORDS)[number]>} */
export function listCategoryCommercialSeoRecords() {
  return RECORDS;
}
